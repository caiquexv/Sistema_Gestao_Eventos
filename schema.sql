-- ---------- Cadastros base ----------
CREATE TABLE serie (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  varchar(150) NOT NULL UNIQUE
);

CREATE TABLE organizacao (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  varchar(150) NOT NULL,
    tipo  varchar(50)
);

CREATE TABLE pessoa (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   varchar(120) NOT NULL,
    email  varchar(160) NOT NULL UNIQUE
);

CREATE TABLE espaco (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        varchar(100) NOT NULL UNIQUE,
    capacidade  integer NOT NULL CHECK (capacidade > 0)
);

CREATE TABLE recurso (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  varchar(60) NOT NULL UNIQUE
);

-- ---------- Estrutura do evento ----------
CREATE TABLE evento (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serie_id     bigint REFERENCES serie(id) ON DELETE SET NULL ON UPDATE CASCADE,
    nome         varchar(150) NOT NULL,
    data_inicio  date NOT NULL,
    data_fim     date NOT NULL,
    CONSTRAINT periodo_valido CHECK (data_fim >= data_inicio)
);

CREATE TABLE atividade (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id  bigint NOT NULL REFERENCES evento(id) ON DELETE CASCADE ON UPDATE CASCADE,
    titulo     varchar(150) NOT NULL,
    descricao  text,
    tipo       varchar(40) NOT NULL
               CHECK (tipo IN ('palestra','workshop','minicurso','painel','mesa-redonda','apresentacao'))
);

CREATE TABLE sessao (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atividade_id      bigint NOT NULL REFERENCES atividade(id) ON DELETE CASCADE ON UPDATE CASCADE,
    espaco_id         bigint NOT NULL REFERENCES espaco(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    data              date NOT NULL,
    hora_inicio       time NOT NULL,
    hora_fim          time NOT NULL,
    duracao           interval GENERATED ALWAYS AS (hora_fim - hora_inicio) STORED,
    requer_inscricao  boolean NOT NULL DEFAULT false,
    limite_vagas      integer,
    CONSTRAINT horario_valido CHECK (hora_fim > hora_inicio),
    CONSTRAINT limite_vagas_positivo CHECK (limite_vagas IS NULL OR limite_vagas > 0)
);

-- ---------- Promocao e recursos ----------
CREATE TABLE promocao_pessoa (
    evento_id  bigint NOT NULL REFERENCES evento(id) ON DELETE CASCADE ON UPDATE CASCADE,
    pessoa_id  bigint NOT NULL REFERENCES pessoa(id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (evento_id, pessoa_id)
);

CREATE TABLE promocao_organizacao (
    evento_id       bigint NOT NULL REFERENCES evento(id) ON DELETE CASCADE ON UPDATE CASCADE,
    organizacao_id  bigint NOT NULL REFERENCES organizacao(id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (evento_id, organizacao_id)
);

CREATE TABLE espaco_recurso (
    espaco_id   bigint NOT NULL REFERENCES espaco(id) ON DELETE CASCADE ON UPDATE CASCADE,
    recurso_id  bigint NOT NULL REFERENCES recurso(id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (espaco_id, recurso_id)
);

-- ---------- Papeis das pessoas ----------
CREATE TABLE papel_evento (
    pessoa_id  bigint NOT NULL REFERENCES pessoa(id) ON DELETE CASCADE ON UPDATE CASCADE,
    evento_id  bigint NOT NULL REFERENCES evento(id) ON DELETE CASCADE ON UPDATE CASCADE,
    papel      varchar(30) NOT NULL DEFAULT 'organizador'
               CHECK (papel IN ('organizador','coordenador')),
    PRIMARY KEY (pessoa_id, evento_id, papel)
);

CREATE TABLE papel_atividade (
    pessoa_id     bigint NOT NULL REFERENCES pessoa(id) ON DELETE CASCADE ON UPDATE CASCADE,
    atividade_id  bigint NOT NULL REFERENCES atividade(id) ON DELETE CASCADE ON UPDATE CASCADE,
    papel         varchar(30) NOT NULL
                  CHECK (papel IN ('palestrante','instrutor','mediador')),
    PRIMARY KEY (pessoa_id, atividade_id, papel)
);

-- ---------- Inscricoes ----------
CREATE TABLE inscricao_evento (
    pessoa_id       bigint NOT NULL REFERENCES pessoa(id) ON DELETE CASCADE ON UPDATE CASCADE,
    evento_id       bigint NOT NULL REFERENCES evento(id) ON DELETE CASCADE ON UPDATE CASCADE,
    status          varchar(20) NOT NULL DEFAULT 'confirmada'
                    CHECK (status IN ('confirmada','cancelada')),
    data_inscricao  timestamp NOT NULL DEFAULT now(),
    PRIMARY KEY (pessoa_id, evento_id)
);

CREATE TABLE inscricao_sessao (
    pessoa_id       bigint NOT NULL REFERENCES pessoa(id) ON DELETE CASCADE ON UPDATE CASCADE,
    sessao_id       bigint NOT NULL REFERENCES sessao(id) ON DELETE CASCADE ON UPDATE CASCADE,
    status          varchar(20) NOT NULL DEFAULT 'confirmada'
                    CHECK (status IN ('confirmada','cancelada')),
    data_inscricao  timestamp NOT NULL DEFAULT now(),
    PRIMARY KEY (pessoa_id, sessao_id)
);

-- ---------- Historico ----------
CREATE TABLE historico_sessao (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id             bigint NOT NULL REFERENCES sessao(id) ON DELETE CASCADE ON UPDATE CASCADE,
    data_anterior         date NOT NULL,
    hora_inicio_anterior  time NOT NULL,
    hora_fim_anterior     time NOT NULL,
    espaco_anterior_id    bigint NOT NULL REFERENCES espaco(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    data_nova             date NOT NULL,
    hora_inicio_nova      time NOT NULL,
    hora_fim_nova         time NOT NULL,
    espaco_novo_id        bigint NOT NULL REFERENCES espaco(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    alterado_em           timestamp NOT NULL DEFAULT now()
);

