CREATE VIEW vw_vagas_sessao AS
SELECT s.atividade_id,s.num_sessao,a.evento_id,s.status,s.inscricao_adicional,
       l.espaco_id,p.capacidade,
       CASE WHEN s.inscricao_adicional AND l.espaco_id IS NOT NULL
            THEN coalesce(s.limite_vagas,p.capacidade) END AS limite_efetivo,
       count(i.inscricao_id) FILTER (WHERE i.status='confirmada') AS confirmadas,
       count(i.inscricao_id) FILTER (WHERE i.status='espera') AS em_espera,
       CASE WHEN s.inscricao_adicional AND l.espaco_id IS NOT NULL
            THEN coalesce(s.limite_vagas,p.capacidade)-count(i.inscricao_id) FILTER (WHERE i.status='confirmada') END AS vagas_disp
FROM sessao s JOIN atividade a USING (atividade_id)
LEFT JOIN alocacao l USING (atividade_id,num_sessao)
LEFT JOIN espaco p USING (espaco_id)
LEFT JOIN inscricao_sessao i USING (atividade_id,num_sessao)
GROUP BY s.atividade_id,s.num_sessao,a.evento_id,l.espaco_id,p.capacidade;
CREATE VIEW vw_inscricao_sessao AS
SELECT i.*,f.posicao_lista_espera FROM inscricao_sessao i
LEFT JOIN (
    SELECT inscricao_id,atividade_id,num_sessao,
           row_number() OVER (PARTITION BY atividade_id,num_sessao ORDER BY data_inscricao,inscricao_id) AS posicao_lista_espera
    FROM inscricao_sessao WHERE status='espera'
) f USING (inscricao_id,atividade_id,num_sessao);
COMMIT;
