BEGIN;
SET LOCAL search_path = public;

-- 1. Cadastros e especializacao total/disjunta de Agente
CREATE TABLE serie (
    serie_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(150) NOT NULL CHECK (btrim(nome) <> '')
);
CREATE TABLE agente (
    agente_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(160) NOT NULL CHECK (btrim(email) <> '')
);
CREATE TABLE pessoa (
    agente_id bigint PRIMARY KEY REFERENCES agente ON DELETE CASCADE ON UPDATE CASCADE,
    nome varchar(120) NOT NULL CHECK (btrim(nome) <> ''),
    cpf varchar(11) UNIQUE CHECK (cpf IS NULL OR cpf ~ '^[0-9]{11}$')
);
CREATE TABLE empresa (
    agente_id bigint PRIMARY KEY REFERENCES agente ON DELETE CASCADE ON UPDATE CASCADE,
    nome varchar(150) NOT NULL CHECK (btrim(nome) <> ''),
    cnpj varchar(14) UNIQUE CHECK (cnpj IS NULL OR cnpj ~ '^[0-9]{14}$')
);
CREATE TABLE organizacao (
    agente_id bigint PRIMARY KEY REFERENCES agente ON DELETE CASCADE ON UPDATE CASCADE,
    nome_org varchar(150) NOT NULL CHECK (btrim(nome_org) <> '')
);
CREATE TABLE agente_telefone (
    agente_id bigint REFERENCES agente ON DELETE CASCADE ON UPDATE CASCADE,
    telefone varchar(25) NOT NULL CHECK (btrim(telefone) <> ''),
    PRIMARY KEY (agente_id, telefone)
);
CREATE TABLE espaco (
    espaco_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(100) NOT NULL CHECK (btrim(nome) <> ''),
    tipo varchar(50) NOT NULL CHECK (btrim(tipo) <> ''),
    capacidade integer NOT NULL CHECK (capacidade > 0),
    rua varchar(180),
    cep varchar(8) CHECK (cep IS NULL OR cep ~ '^[0-9]{8}$'),
    numero varchar(20)
);
CREATE TABLE recurso (
    recurso_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(80) NOT NULL UNIQUE CHECK (btrim(nome) <> ''),
    descricao text,
    unidade_medida varchar(30) NOT NULL DEFAULT 'unidade'
        CHECK (btrim(unidade_medida) <> '')
);

-- 2. Eventos, edicoes, atividades e sessoes (entidade fraca)
CREATE TABLE evento (
    evento_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serie_id bigint REFERENCES serie ON DELETE RESTRICT ON UPDATE CASCADE,
    num_edicao integer,
    nome varchar(150) NOT NULL CHECK (btrim(nome) <> ''),
    descricao text,
    tipo varchar(50) NOT NULL CHECK (btrim(tipo) <> ''),
    data_inicio date NOT NULL,
    data_fim date NOT NULL,
    status varchar(15) NOT NULL DEFAULT 'planejado'
        CHECK (status IN ('planejado','ativo','encerrado','cancelado')),
    CHECK (data_fim >= data_inicio),
    CHECK ((serie_id IS NULL AND num_edicao IS NULL)
        OR (serie_id IS NOT NULL AND num_edicao IS NOT NULL AND num_edicao > 0)),
    UNIQUE (serie_id, num_edicao)
);
CREATE TABLE promocao_evento (
    evento_id bigint REFERENCES evento ON DELETE CASCADE ON UPDATE CASCADE,
    agente_id bigint REFERENCES agente ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (evento_id, agente_id)
);
CREATE TABLE atividade (
    atividade_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id bigint NOT NULL REFERENCES evento ON DELETE CASCADE ON UPDATE CASCADE,
    titulo varchar(150) NOT NULL CHECK (btrim(titulo) <> ''),
    descricao text,
    tipo_atividade varchar(40) NOT NULL CHECK (tipo_atividade IN
        ('palestra','workshop','minicurso','painel','mesa-redonda','apresentacao'))
);
CREATE TABLE sessao (
    atividade_id bigint REFERENCES atividade ON DELETE CASCADE ON UPDATE CASCADE,
    num_sessao integer CHECK (num_sessao > 0),
    data_hora_inicio timestamp NOT NULL,
    data_hora_fim timestamp NOT NULL,
    duracao interval GENERATED ALWAYS AS (data_hora_fim - data_hora_inicio) STORED,
    status varchar(15) NOT NULL DEFAULT 'planejada'
        CHECK (status IN ('planejada','confirmada','cancelada')),
    inscricao_adicional boolean NOT NULL DEFAULT false,
    limite_vagas integer CHECK (limite_vagas IS NULL OR limite_vagas > 0),
    PRIMARY KEY (atividade_id, num_sessao),
    CHECK (data_hora_fim > data_hora_inicio),
    CHECK (inscricao_adicional OR limite_vagas IS NULL)
);

-- 3. Disponibilidade, alocacao corrente e quantidades de recursos
CREATE TABLE evento_espaco (
    evento_id bigint REFERENCES evento ON DELETE CASCADE ON UPDATE CASCADE,
    espaco_id bigint REFERENCES espaco ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (evento_id, espaco_id)
);
CREATE TABLE espaco_recurso (
    espaco_id bigint REFERENCES espaco ON DELETE CASCADE ON UPDATE CASCADE,
    recurso_id bigint REFERENCES recurso ON DELETE RESTRICT ON UPDATE CASCADE,
    quantidade_disponivel integer NOT NULL CHECK (quantidade_disponivel >= 0),
    PRIMARY KEY (espaco_id, recurso_id)
);
CREATE TABLE sessao_recurso_necessario (
    atividade_id bigint,
    num_sessao integer,
    recurso_id bigint REFERENCES recurso ON DELETE RESTRICT ON UPDATE CASCADE,
    quantidade_necessaria integer NOT NULL CHECK (quantidade_necessaria > 0),
    PRIMARY KEY (atividade_id, num_sessao, recurso_id),
    FOREIGN KEY (atividade_id, num_sessao) REFERENCES sessao
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE alocacao (
    alocacao_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atividade_id bigint NOT NULL,
    num_sessao integer NOT NULL,
    espaco_id bigint NOT NULL REFERENCES espaco ON DELETE RESTRICT ON UPDATE CASCADE,
    data date NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'America/Sao_Paulo')::date,
    status_alocacao varchar(15) NOT NULL DEFAULT 'planejada'
        CHECK (status_alocacao IN ('planejada','confirmada','cancelada')),
    UNIQUE (atividade_id, num_sessao),
    FOREIGN KEY (atividade_id, num_sessao) REFERENCES sessao
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE alocacao_recurso (
    alocacao_id bigint REFERENCES alocacao ON DELETE CASCADE ON UPDATE CASCADE,
    recurso_id bigint REFERENCES recurso ON DELETE RESTRICT ON UPDATE CASCADE,
    quantidade_alocada integer NOT NULL CHECK (quantidade_alocada > 0),
    PRIMARY KEY (alocacao_id, recurso_id)
);

-- 4. Papeis independentes e inscricoes correntes
CREATE TABLE papel_evento (
    pessoa_id bigint REFERENCES pessoa(agente_id) ON DELETE CASCADE ON UPDATE CASCADE,
    evento_id bigint REFERENCES evento ON DELETE CASCADE ON UPDATE CASCADE,
    funcao varchar(30) CHECK (funcao IN ('organizador','coordenador')),
    PRIMARY KEY (pessoa_id, evento_id, funcao)
);
CREATE TABLE papel_sessao (
    pessoa_id bigint REFERENCES pessoa(agente_id) ON DELETE CASCADE ON UPDATE CASCADE,
    atividade_id bigint,
    num_sessao integer,
    papel varchar(30) CHECK (papel IN ('palestrante','instrutor','mediador')),
    PRIMARY KEY (pessoa_id, atividade_id, num_sessao, papel),
    FOREIGN KEY (atividade_id, num_sessao) REFERENCES sessao
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE inscricao_evento (
    inscricao_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pessoa_id bigint NOT NULL REFERENCES pessoa(agente_id) ON DELETE CASCADE ON UPDATE CASCADE,
    evento_id bigint NOT NULL REFERENCES evento ON DELETE CASCADE ON UPDATE CASCADE,
    data_inscricao timestamp NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'America/Sao_Paulo'),
    status varchar(15) NOT NULL DEFAULT 'confirmada'
        CHECK (status IN ('confirmada','cancelada')),
    UNIQUE (pessoa_id, evento_id)
);
CREATE TABLE inscricao_sessao (
    inscricao_id bigint REFERENCES inscricao_evento ON DELETE CASCADE ON UPDATE CASCADE,
    atividade_id bigint,
    num_sessao integer,
    data_inscricao timestamp NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'America/Sao_Paulo'),
    status varchar(15) NOT NULL DEFAULT 'confirmada'
        CHECK (status IN ('confirmada','espera','cancelada')),
    PRIMARY KEY (inscricao_id, atividade_id, num_sessao),
    FOREIGN KEY (atividade_id, num_sessao) REFERENCES sessao
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX ix_atividade_evento ON atividade(evento_id);
CREATE INDEX ix_alocacao_espaco ON alocacao(espaco_id);
CREATE INDEX ix_inscricao_evento_evento ON inscricao_evento(evento_id);
CREATE INDEX ix_inscricao_sessao_fila ON inscricao_sessao
    (atividade_id, num_sessao, status, data_inscricao, inscricao_id);

-- 5. Concorrencia: uma escrita de dominio por vez ate COMMIT/ROLLBACK.
-- Opção simples e deliberada para este prototipo pequeno; SELECTs nao sao bloqueados.
-- Escritas usam READ COMMITTED para que as validacoes vejam o ultimo COMMIT.
CREATE FUNCTION fn_serializar_escrita() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
BEGIN
    IF TG_OP = 'TRUNCATE' THEN
        RAISE EXCEPTION 'Use DELETE em transacao; TRUNCATE nao preserva as validacoes do dominio.'
            USING ERRCODE = '0A000';
    END IF;
    IF current_setting('transaction_isolation') <> 'read committed' THEN
        RAISE EXCEPTION 'Escritas deste prototipo exigem isolamento READ COMMITTED.'
            USING ERRCODE = '0A000';
    END IF;
    PERFORM pg_advisory_xact_lock(6400, 202602);
    RETURN NULL;
END;
$$;

-- Finalidade: especializacao total/disjunta e participacoes minimas.
CREATE FUNCTION fn_validar_cadastros() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
DECLARE v_id bigint;
BEGIN
    SELECT a.agente_id INTO v_id FROM agente a
    LEFT JOIN pessoa p USING (agente_id)
    LEFT JOIN empresa e USING (agente_id)
    LEFT JOIN organizacao o USING (agente_id)
    WHERE num_nonnulls(p.agente_id, e.agente_id, o.agente_id) <> 1 LIMIT 1;
    IF FOUND THEN
        RAISE EXCEPTION 'Agente % deve pertencer a exatamente um subtipo.', v_id USING ERRCODE='23514';
    END IF;
    SELECT e.evento_id INTO v_id FROM evento e
    WHERE NOT EXISTS (SELECT 1 FROM promocao_evento p WHERE p.evento_id=e.evento_id) LIMIT 1;
    IF FOUND THEN
        RAISE EXCEPTION 'Evento % precisa de pelo menos um promotor.', v_id USING ERRCODE='23514';
    END IF;
    SELECT a.atividade_id INTO v_id FROM atividade a
    WHERE NOT EXISTS (SELECT 1 FROM sessao s WHERE s.atividade_id=a.atividade_id) LIMIT 1;
    IF FOUND THEN
        RAISE EXCEPTION 'Atividade % precisa de pelo menos uma sessao.', v_id USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END;
$$;

-- Finalidade 1: coerencia temporal, inclusive quando evento/atividade mudam.
CREATE FUNCTION fn_validar_periodos() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
DECLARE v record;
BEGIN
    SELECT s.atividade_id,s.num_sessao INTO v FROM sessao s
    JOIN atividade a USING (atividade_id) JOIN evento e USING (evento_id)
    WHERE s.data_hora_inicio < e.data_inicio::timestamp
       OR s.data_hora_fim > (e.data_fim + 1)::timestamp LIMIT 1;
    IF FOUND THEN
        RAISE EXCEPTION 'Sessao (%, %) fora do periodo do evento.',v.atividade_id,v.num_sessao USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END;
$$;

-- Finalidade: alocacao corrente, autorizacao do espaco e capacidade fisica.
CREATE FUNCTION fn_validar_alocacoes() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM alocacao l JOIN atividade a USING (atividade_id)
        WHERE NOT EXISTS (SELECT 1 FROM evento_espaco x
            WHERE x.evento_id=a.evento_id AND x.espaco_id=l.espaco_id)
    ) THEN
        RAISE EXCEPTION 'Espaco da alocacao nao disponibilizado para o evento.' USING ERRCODE='23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM sessao s JOIN atividade a USING (atividade_id)
        JOIN evento e USING (evento_id)
        LEFT JOIN alocacao l USING (atividade_id,num_sessao)
        WHERE (s.status='confirmada' AND (l.alocacao_id IS NULL OR l.status_alocacao<>'confirmada'))
           OR (s.status='cancelada' AND l.status_alocacao<>'cancelada')
           OR (e.status='cancelado' AND s.status<>'cancelada')
    ) THEN
        RAISE EXCEPTION 'Estados de evento, sessao e alocacao incompatíveis.' USING ERRCODE='23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM sessao s JOIN alocacao l USING (atividade_id,num_sessao)
        JOIN espaco p USING (espaco_id) WHERE s.limite_vagas > p.capacidade
    ) THEN
        RAISE EXCEPTION 'Limite da sessao excede a capacidade fisica do espaco.' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END;
$$;

-- Finalidade 2: conflitos de espaco, considerando intervalos [inicio,fim).
CREATE FUNCTION fn_validar_conflitos() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM alocacao l1 JOIN sessao s1 USING (atividade_id,num_sessao)
        JOIN alocacao l2 ON l2.espaco_id=l1.espaco_id AND l2.alocacao_id>l1.alocacao_id
        JOIN sessao s2 ON (s2.atividade_id,s2.num_sessao)=(l2.atividade_id,l2.num_sessao)
        WHERE l1.status_alocacao='confirmada' AND l2.status_alocacao='confirmada'
          AND s1.status<>'cancelada' AND s2.status<>'cancelada'
          AND s1.data_hora_inicio<s2.data_hora_fim AND s2.data_hora_inicio<s1.data_hora_fim
    ) THEN
        RAISE EXCEPTION 'Duas alocacoes confirmadas disputam o mesmo espaco e horario.' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END;
$$;

-- Finalidade 3: recursos necessarios, disponiveis e efetivamente alocados.
CREATE FUNCTION fn_validar_recursos() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM alocacao_recurso u JOIN alocacao l USING (alocacao_id)
        LEFT JOIN espaco_recurso d ON (d.espaco_id,d.recurso_id)=(l.espaco_id,u.recurso_id)
        WHERE l.status_alocacao<>'cancelada'
          AND (d.recurso_id IS NULL OR u.quantidade_alocada>d.quantidade_disponivel)
    ) THEN
        RAISE EXCEPTION 'Recurso alocado ausente ou quantidade superior a disponibilidade do espaco.' USING ERRCODE='23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM sessao s JOIN sessao_recurso_necessario n USING (atividade_id,num_sessao)
        LEFT JOIN alocacao l USING (atividade_id,num_sessao)
        LEFT JOIN alocacao_recurso u ON (u.alocacao_id,u.recurso_id)=(l.alocacao_id,n.recurso_id)
        WHERE s.status='confirmada'
          AND (u.recurso_id IS NULL OR u.quantidade_alocada<n.quantidade_necessaria)
    ) THEN
        RAISE EXCEPTION 'Sessao confirmada sem todos os recursos necessarios.' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END;
$$;

-- Novas inscricoes sao validadas na entrada. Adicionais entram na fila;
-- a confirmacao e resolvida por FIFO no estado final da transacao.
CREATE FUNCTION fn_preparar_inscricao_evento() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
BEGIN
    IF TG_OP='UPDATE' AND pg_trigger_depth()=1 AND
       (NEW.pessoa_id,NEW.evento_id) IS DISTINCT FROM (OLD.pessoa_id,OLD.evento_id) THEN
        RAISE EXCEPTION 'Inscricao no evento nao pode ser transferida; cancele e cadastre o novo vinculo.' USING ERRCODE='23514';
    END IF;
    IF NEW.status='confirmada' AND
       (TG_OP='INSERT' OR OLD.status='cancelada' OR OLD.evento_id IS DISTINCT FROM NEW.evento_id) THEN
        IF NOT EXISTS (SELECT 1 FROM evento WHERE evento_id=NEW.evento_id AND status='ativo') THEN
            RAISE EXCEPTION 'Novas inscricoes exigem evento ativo.' USING ERRCODE='23514';
        END IF;
        IF TG_OP='UPDATE' AND OLD.status='cancelada' THEN
            NEW.data_inscricao := clock_timestamp() AT TIME ZONE 'America/Sao_Paulo';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE FUNCTION fn_preparar_inscricao_sessao() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
BEGIN
    IF TG_OP='UPDATE' AND pg_trigger_depth()=1 AND
       (NEW.inscricao_id,NEW.atividade_id,NEW.num_sessao) IS DISTINCT FROM
       (OLD.inscricao_id,OLD.atividade_id,OLD.num_sessao) THEN
        RAISE EXCEPTION 'Inscricao adicional nao pode ser transferida; cancele e cadastre o novo vinculo.' USING ERRCODE='23514';
    END IF;
    IF NEW.status='cancelada' OR pg_trigger_depth()>1 THEN RETURN NEW; END IF;
    IF TG_OP='UPDATE' AND OLD.status='confirmada' AND NEW.status='confirmada' THEN RETURN NEW; END IF;
    IF NOT EXISTS (
        SELECT 1 FROM inscricao_evento i JOIN evento e USING (evento_id)
        JOIN atividade a ON a.evento_id=e.evento_id
        JOIN sessao s ON s.atividade_id=a.atividade_id
        WHERE i.inscricao_id=NEW.inscricao_id AND s.atividade_id=NEW.atividade_id
          AND s.num_sessao=NEW.num_sessao AND i.status='confirmada' AND e.status='ativo'
          AND s.status='confirmada' AND s.inscricao_adicional
    ) THEN
        RAISE EXCEPTION 'Inscricao adicional exige evento ativo, inscricao no mesmo evento e sessao restrita confirmada.' USING ERRCODE='23514';
    END IF;
    IF TG_OP='UPDATE' AND OLD.status='cancelada' THEN
        NEW.data_inscricao := clock_timestamp() AT TIME ZONE 'America/Sao_Paulo';
    END IF;
    NEW.status := 'espera';
    RETURN NEW;
END;
$$;

-- Cancelamentos propagam para os vinculos dependentes na mesma transacao.
CREATE FUNCTION fn_propagar_cancelamento() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
BEGIN
    IF TG_TABLE_NAME='evento' AND NEW.status='cancelado' THEN
        UPDATE sessao s SET status='cancelada' FROM atividade a
        WHERE s.atividade_id=a.atividade_id AND a.evento_id=NEW.evento_id AND s.status<>'cancelada';
        UPDATE inscricao_evento SET status='cancelada'
        WHERE evento_id=NEW.evento_id AND status<>'cancelada';
    ELSIF TG_TABLE_NAME='sessao' AND NEW.status='cancelada' THEN
        UPDATE alocacao SET status_alocacao='cancelada'
        WHERE atividade_id=NEW.atividade_id AND num_sessao=NEW.num_sessao AND status_alocacao<>'cancelada';
        UPDATE inscricao_sessao SET status='cancelada'
        WHERE atividade_id=NEW.atividade_id AND num_sessao=NEW.num_sessao AND status<>'cancelada';
    ELSIF TG_TABLE_NAME='inscricao_evento' AND NEW.status='cancelada' THEN
        UPDATE inscricao_sessao SET status='cancelada'
        WHERE inscricao_id=NEW.inscricao_id AND status<>'cancelada';
    END IF;
    RETURN NULL;
END;
$$;
CREATE FUNCTION fn_validar_transicao_evento() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
BEGIN
    IF OLD.status<>NEW.status AND NOT (
        (OLD.status='planejado' AND NEW.status IN ('ativo','cancelado')) OR
        (OLD.status='ativo' AND NEW.status IN ('encerrado','cancelado'))
    ) THEN
        RAISE EXCEPTION 'Transicao de evento nao permitida: % -> %.',OLD.status,NEW.status USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;

-- Finalidade 4: integridade de inscricoes, capacidade e promocao FIFO.
CREATE FUNCTION fn_validar_inscricoes_fila() RETURNS trigger
LANGUAGE plpgsql VOLATILE SET search_path = public, pg_temp AS $$
DECLARE v record; v_confirmadas integer; v_vagas integer;
BEGIN
    IF EXISTS (
        SELECT 1 FROM inscricao_sessao i JOIN inscricao_evento e USING (inscricao_id)
        JOIN atividade a ON a.atividade_id=i.atividade_id
        JOIN sessao s ON (s.atividade_id,s.num_sessao)=(i.atividade_id,i.num_sessao)
        WHERE e.evento_id<>a.evento_id OR
          (i.status<>'cancelada' AND (e.status<>'confirmada' OR s.status<>'confirmada' OR NOT s.inscricao_adicional))
    ) THEN
        RAISE EXCEPTION 'Vinculos ou estados de inscricao adicional invalidos.' USING ERRCODE='23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM inscricao_evento i JOIN evento e USING (evento_id)
        WHERE e.status='cancelado' AND i.status<>'cancelada'
    ) THEN
        RAISE EXCEPTION 'Evento cancelado nao pode manter inscricoes ativas.' USING ERRCODE='23514';
    END IF;
    FOR v IN
        SELECT s.atividade_id,s.num_sessao,coalesce(s.limite_vagas,p.capacidade) AS limite,e.status AS evento_status
        FROM sessao s JOIN alocacao l USING (atividade_id,num_sessao)
        JOIN espaco p USING (espaco_id) JOIN atividade a USING (atividade_id) JOIN evento e USING (evento_id)
        WHERE s.inscricao_adicional AND s.status='confirmada' AND l.status_alocacao='confirmada'
        ORDER BY s.atividade_id,s.num_sessao
    LOOP
        SELECT count(*) INTO v_confirmadas FROM inscricao_sessao
        WHERE atividade_id=v.atividade_id AND num_sessao=v.num_sessao AND status='confirmada';
        IF v_confirmadas>v.limite THEN
            RAISE EXCEPTION 'Confirmacoes excedem o limite da sessao (%, %).',v.atividade_id,v.num_sessao USING ERRCODE='23514';
        END IF;
        v_vagas := v.limite-v_confirmadas;
        IF v_vagas>0 AND v.evento_status='ativo' THEN
            WITH candidatas AS (
                SELECT i.inscricao_id,i.atividade_id,i.num_sessao FROM inscricao_sessao i
                JOIN inscricao_evento e USING (inscricao_id)
                WHERE i.atividade_id=v.atividade_id AND i.num_sessao=v.num_sessao
                  AND i.status='espera' AND e.status='confirmada'
                ORDER BY i.data_inscricao,i.inscricao_id LIMIT v_vagas
            )
            UPDATE inscricao_sessao i SET status='confirmada' FROM candidatas c
            WHERE (i.inscricao_id,i.atividade_id,i.num_sessao)=(c.inscricao_id,c.atividade_id,c.num_sessao);
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;

-- 6. Instalacao dos gatilhos em todos os caminhos de alteracao pertinentes.
DO $$
DECLARE t text; r record;
BEGIN
    FOREACH t IN ARRAY ARRAY['serie','agente','pessoa','empresa','organizacao','agente_telefone',
        'espaco','recurso','evento','promocao_evento','atividade','sessao','evento_espaco',
        'espaco_recurso','sessao_recurso_necessario','alocacao','alocacao_recurso',
        'papel_evento','papel_sessao','inscricao_evento','inscricao_sessao']
    LOOP
        EXECUTE format('CREATE TRIGGER tg_00_escrita BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION fn_serializar_escrita()',t);
    END LOOP;
