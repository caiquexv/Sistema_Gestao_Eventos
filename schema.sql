-- Trigger 1: coerencia temporal (a sessao precisa caber no periodo do evento)
CREATE OR REPLACE FUNCTION fn_sessao_coerencia_temporal()
RETURNS trigger AS $$
DECLARE
    v_inicio date;
    v_fim    date;
BEGIN
    SELECT e.data_inicio, e.data_fim
      INTO v_inicio, v_fim
      FROM atividade a
      JOIN evento e ON e.id = a.evento_id
     WHERE a.id = NEW.atividade_id;

    IF NEW.data < v_inicio OR NEW.data > v_fim THEN
        RAISE EXCEPTION 'A data da sessao (%) esta fora do periodo do evento (% a %).',
            NEW.data, v_inicio, v_fim;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_sessao_coerencia_temporal
    BEFORE INSERT OR UPDATE ON sessao
    FOR EACH ROW EXECUTE FUNCTION fn_sessao_coerencia_temporal();

-- Trigger 2: conflito de espaco (duas sessoes no mesmo espaco com horario sobreposto)
CREATE OR REPLACE FUNCTION fn_sessao_conflito_espaco()
RETURNS trigger AS $$
DECLARE
    v_conflitos integer;
BEGIN
    SELECT count(*)
      INTO v_conflitos
      FROM sessao s
     WHERE s.espaco_id = NEW.espaco_id
       AND s.data = NEW.data
       AND s.id <> NEW.id
       AND NEW.hora_inicio < s.hora_fim
       AND NEW.hora_fim > s.hora_inicio;

    IF v_conflitos > 0 THEN
        RAISE EXCEPTION 'Conflito de espaco: o espaco % ja possui sessao sobreposta no dia %.',
            NEW.espaco_id, NEW.data;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_sessao_conflito_espaco
    BEFORE INSERT OR UPDATE ON sessao
    FOR EACH ROW EXECUTE FUNCTION fn_sessao_conflito_espaco();

-- Trigger 3: admissao em sessao (inscricao confirmada no evento + limite de vagas)
CREATE OR REPLACE FUNCTION fn_inscricao_sessao_admissao()
RETURNS trigger AS $$
DECLARE
    v_evento_id       bigint;
    v_limite_vagas    integer;
    v_capacidade      integer;
    v_limite_efetivo  integer;
    v_ocupacao        integer;
    v_inscrito_evento integer;
BEGIN
    IF NEW.status <> 'confirmada' THEN
        RETURN NEW;
    END IF;

    SELECT e.id, s.limite_vagas, ep.capacidade
      INTO v_evento_id, v_limite_vagas, v_capacidade
      FROM sessao s
      JOIN atividade a ON a.id = s.atividade_id
      JOIN evento e    ON e.id = a.evento_id
      JOIN espaco ep   ON ep.id = s.espaco_id
     WHERE s.id = NEW.sessao_id;

    SELECT count(*)
      INTO v_inscrito_evento
      FROM inscricao_evento ie
     WHERE ie.pessoa_id = NEW.pessoa_id
       AND ie.evento_id = v_evento_id
       AND ie.status = 'confirmada';

    IF v_inscrito_evento = 0 THEN
        RAISE EXCEPTION 'A pessoa % nao possui inscricao confirmada no evento % da sessao.',
            NEW.pessoa_id, v_evento_id;
    END IF;

    v_limite_efetivo := COALESCE(v_limite_vagas, v_capacidade);

    SELECT count(*)
      INTO v_ocupacao
      FROM inscricao_sessao i
     WHERE i.sessao_id = NEW.sessao_id
       AND i.status = 'confirmada'
       AND NOT (i.pessoa_id = NEW.pessoa_id AND i.sessao_id = NEW.sessao_id);

    IF v_ocupacao + 1 > v_limite_efetivo THEN
        RAISE EXCEPTION 'Sessao % lotada: limite de % participantes atingido.',
            NEW.sessao_id, v_limite_efetivo;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_inscricao_sessao_admissao
    BEFORE INSERT OR UPDATE ON inscricao_sessao
    FOR EACH ROW EXECUTE FUNCTION fn_inscricao_sessao_admissao();

-- Trigger 4: historico de programacao (grava mudanca de data, horario ou espaco)
CREATE OR REPLACE FUNCTION fn_sessao_historico()
RETURNS trigger AS $$
BEGIN
    IF (OLD.data, OLD.hora_inicio, OLD.hora_fim, OLD.espaco_id)
       IS DISTINCT FROM
       (NEW.data, NEW.hora_inicio, NEW.hora_fim, NEW.espaco_id) THEN

        INSERT INTO historico_sessao (
            sessao_id,
            data_anterior, hora_inicio_anterior, hora_fim_anterior, espaco_anterior_id,
            data_nova, hora_inicio_nova, hora_fim_nova, espaco_novo_id
        ) VALUES (
            OLD.id,
            OLD.data, OLD.hora_inicio, OLD.hora_fim, OLD.espaco_id,
            NEW.data, NEW.hora_inicio, NEW.hora_fim, NEW.espaco_id
        );
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_sessao_historico
    AFTER UPDATE ON sessao
    FOR EACH ROW EXECUTE FUNCTION fn_sessao_historico();
